import math

print("The floor and the ceiling of 23.56 are:",str(math.floor(23.56)),",",str(math.ceil(23.56)))

x=10
y=-56

print("The value of x after copying the sign of y is:",str(math.copysign(x,y)))

print('The absolute value of 10 and -56 is'+str(math.fabs(10))+","+str(math.fabs(-56)))

print("The gcd of 8 and 56 is",str(math.gcd(8,56)))